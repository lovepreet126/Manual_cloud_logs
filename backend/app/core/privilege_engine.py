class PrivilegeEngine:
    @staticmethod
    def get_activities_for_cloud(cloud: str) -> List[ActivityDefinition]:
        return [act for act in ACTIVITIES_REGISTRY.values() if act.cloud == cloud.lower()]

    @staticmethod
    def get_activity_by_id(activity_id: str) -> Optional[ActivityDefinition]:
        return ACTIVITIES_REGISTRY.get(activity_id)

    @staticmethod
    def is_activity_unlocked(
        activity: ActivityDefinition,
        current_privilege_level: int,
        unlocked_levels: List[int],
        god_mode: bool = False,
    ) -> bool:
        if god_mode:
            return True
        # Must have reached or unlocked the required privilege level
        return activity.required_privilege_level <= current_privilege_level or (
            activity.required_privilege_level in unlocked_levels
        )
